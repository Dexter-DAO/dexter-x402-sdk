#!/usr/bin/env node
// Unicode 16.0.0, UTS #39. Run with an optional local confusables.txt path.
import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';

const version = '16.0.0';
const source = `https://www.unicode.org/Public/security/${version}/confusables.txt`;
const expectedSha256 = '95bd0aad6dced5ebc63436f459c06ab21a8d107cd842fb57f5c3a1e91bca8611';
const bytes = process.argv[2]
  ? await readFile(process.argv[2])
  : Buffer.from(await (await fetch(source)).arrayBuffer());
if (createHash('sha256').update(bytes).digest('hex') !== expectedSha256) {
  throw new Error('confusables_source_mismatch');
}
const mappings = [];
for (const line of bytes.toString('utf8').split('\n')) {
  const match = /^([0-9A-F]+)\s*;\s*([0-9A-F ]+)\s*;/.exec(line);
  if (!match) continue;
  const prototype = String.fromCodePoint(...match[2].trim().split(/\s+/).map((hex) => parseInt(hex, 16)));
  if (/^[a-z0-9.-]+$/.test(prototype)) mappings.push([parseInt(match[1], 16), prototype]);
}
mappings.sort((a, b) => a[0] - b[0]);
const output = `// Generated by scripts/generate-seller-confusables.mjs.\n// Unicode ${version}, UTS #39: ${source}\n// Source SHA-256: ${expectedSha256}\n// Unicode data license: https://www.unicode.org/license.txt\nexport const ASCII_CONFUSABLES: Readonly<Record<number, string>> = {\n${mappings.map(([cp, prototype]) => `  0x${cp.toString(16)}: ${JSON.stringify(prototype)},`).join('\n')}\n};\n`;
await writeFile(new URL('../src/seller/confusables.ts', import.meta.url), output);
console.log(JSON.stringify({ version, mappings: mappings.length, sourceSha256: expectedSha256 }));
